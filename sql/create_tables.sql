CREATE TABLE jobs(
    work_year INT,
    experience_level VARCHAR(10),
    employment_type VARCHAR(10),
    job_title VARCHAR(255),
    salary BIGINT,
    salary_currency VARCHAR(20),
    salary_in_usd BIGINT,
    employee_residence VARCHAR(20),
    remote_ratio INT,
    company_location VARCHAR(20),
    company_size VARCHAR(10),
    experience_level_name VARCHAR(50),
    employment_type_name VARCHAR(50),
    salary_category VARCHAR(50)
);